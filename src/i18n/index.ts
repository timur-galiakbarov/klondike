type Locale = keyof typeof translations;
export type AppLocale = Locale;
export type LocaleSetting = 'system' | AppLocale;
type TranslationKey = keyof (typeof translations)['ru'];
type Params = Record<string, string | number>;

const normalizeLocale = (locale: string | undefined | null): Locale => {
  const base = locale?.toLowerCase().split(/[-_]/)[0];
  if (
    base === 'en' ||
    base === 'tr' ||
    base === 'hi' ||
    base === 'fr' ||
    base === 'it' ||
    base === 'pt' ||
    base === 'nl' ||
    base === 'pl'
  ) {
    return base;
  }
  return 'ru';
};

let currentLocale: AppLocale = normalizeLocale(Intl.DateTimeFormat().resolvedOptions().locale);

export const resolveLocale = (localeSetting?: LocaleSetting | null): AppLocale => {
  if (!localeSetting || localeSetting === 'system') {
    return normalizeLocale(Intl.DateTimeFormat().resolvedOptions().locale);
  }
  return normalizeLocale(localeSetting);
};

export const setLocale = (localeSetting?: LocaleSetting | null) => {
  currentLocale = resolveLocale(localeSetting);
};

export const getLocale = () => currentLocale;

const interpolate = (template: string, params?: Params) => {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
};

export const t = (key: TranslationKey, params?: Params) => {
  const value = translations[currentLocale][key] ?? translations.ru[key];
  return interpolate(value, params);
};

export const getTrackingStatusLabel = (
  status: 'unavailable' | 'denied' | 'granted' | 'restricted' | 'undetermined'
) => {
  switch (status) {
    case 'unavailable':
      return t('trackingUnavailable');
    case 'denied':
      return t('trackingDenied');
    case 'granted':
      return t('trackingGranted');
    case 'restricted':
      return t('trackingRestricted');
    case 'undetermined':
      return t('trackingUndetermined');
    default:
      return status;
  }
};

